    summary_count = fields.Integer(compute='_compute_counts', string='Summary Count')
    detail_count = fields.Integer(compute='_compute_counts', string='Detail Count')
    company_id = fields.Many2one('res.company', string='Company', default=lambda self: self.env.company)
    notes = fields.Text(string='Internal Notes')

    @api.depends('summary_line_ids', 'detail_line_ids')
    def _compute_counts(self):
        for rec in self:
            rec.summary_count = len(rec.summary_line_ids)
            rec.detail_count = len(rec.detail_line_ids)

    @api.depends('pdf_file')
    def _compute_pdf_checksum(self):
        for rec in self:
            try:
                content = base64.b64decode(rec.pdf_file or b'', validate=True)
            except (ValueError, TypeError):
                content = b''
            rec.pdf_checksum = hashlib.sha256(content).hexdigest() if content else False

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if vals.get('name', _('New')) == _('New'):
                vals['name'] = self.env['ir.sequence'].next_by_code('npsb.settlement.report') or _('New')
        return super().create(vals_list)

    def action_process_pdf(self):
        self.ensure_one()
        if not self.pdf_file:
            raise UserError(_('Please upload a PDF file first.'))
        duplicate = self.env['npsb.settlement.report']
        if self.pdf_checksum:
            duplicate = self.search([
                ('id', '!=', self.id),
                ('company_id', '=', self.company_id.id),
                ('pdf_checksum', '=', self.pdf_checksum),
                ('state', '=', 'processed'),
            ], limit=1)
        if duplicate:
            raise UserError(_(
                'This NPSB Settlement PDF was already processed in %s.'
            ) % duplicate.display_name)
        if pdfplumber is None:
            raise UserError(_('Python library "pdfplumber" is required. Install: pip install pdfplumber'))

        self.summary_line_ids.unlink()
        self.detail_line_ids.unlink()
        log = []

        try:
            pdf_content = base64.b64decode(self.pdf_file)
            with pdfplumber.open(io.BytesIO(pdf_content)) as pdf:
                log.append(f'PDF opened. Total pages: {len(pdf.pages)}')
                page1_text = pdf.pages[0].extract_text() or ''
                self._extract_metadata(page1_text, log)

                summary_rows = self._parse_summary_page(pdf.pages[0], log)
                self._create_summary_lines(summary_rows, log)

                detail_rows = []
                for page_idx, page in enumerate(pdf.pages[1:], start=2):
                    page_text = page.extract_text() or ''
                    channel = self._detect_channel(page_text)
                    if channel:
                        log.append(f'Page {page_idx}: channel = {channel}')
                        detail_rows.extend(self._parse_detail_page(page, channel, log))
                    else:
                        log.append(f'Page {page_idx}: channel not detected')

                self._create_detail_lines(detail_rows, log)

            self.state = 'processed'
            log.append('Processing completed successfully.')
            self.processing_log = '\n'.join(log)
            self.message_post(
                body=_('PDF processed. Summary: %s lines | Details: %s lines')
                     % (self.summary_count, self.detail_count)
            )
        except Exception as e:
            self.state = 'error'
            log.append(f'ERROR: {str(e)}')
            self.processing_log = '\n'.join(log)
            raise UserError(_('Failed to process PDF:\n%s') % str(e))
        return True

    # ------------------------------------------------------------------
    # Metadata
    # ------------------------------------------------------------------
    def _extract_metadata(self, text, log):
        m = re.search(r'TransactionBusinessDate\s*:\s*(\d{1,2}[-/]\w{3}[-/]\d{4})', text, re.I)
        if not m:
            m = re.search(r'Transaction\s*Business\s*Date\s*[:\-]?\s*(\d{1,2}[-/]\w{3}[-/]\d{4})', text, re.I)
        if m:
            self.transaction_date = self._parse_date(m.group(1))
            log.append(f'Transaction date: {self.transaction_date}')

        m = re.search(r'SettlementBusinessDate\s*:\s*(\d{1,2}[-/]\w{3}[-/]\d{4})', text, re.I)
        if not m:
            m = re.search(r'Settlement\s*Business\s*Date\s*[:\-]?\s*(\d{1,2}[-/]\w{3}[-/]\d{4})', text, re.I)
        if m:
            self.settlement_date = self._parse_date(m.group(1))
            log.append(f'Settlement date: {self.settlement_date}')

        m = re.search(r'GeneratedBy\s*:\s*(.+?)(?:on\d|/Developed|$)', text, re.I)
        if not m:
            m = re.search(r'Generated\s*By\s*[:\-]?\s*(.+?)(?:\s+on\s+|\n|$)', text, re.I)
        if m:
            self.generated_by = m.group(1).strip()
            log.append(f'Generated by: {self.generated_by}')

        m = re.search(r'on\s*(\d{1,2}/\d{1,2}/\d{4}\s*\d{1,2}:\d{2}:\d{2}\s*[AP]M)', text, re.I)
        if m:
            try:
                self.generation_datetime = datetime.strptime(
                    m.group(1).strip(), '%d/%m/%Y %I:%M:%S %p'
                )
            except Exception:
                pass

        m = re.search(r'(?:Summary|Settlement)\s*Position\s*of\s*(.+?)(?:\n|Transaction|$)', text, re.I)
        if m:
            bank = re.sub(r'\s+', ' ', m.group(1)).strip()
            if bank:
                self.bank_name = bank
                log.append(f'Bank name: {self.bank_name}')

    def _parse_date(self, date_str):
        for fmt in ('%d-%b-%Y', '%d/%b/%Y', '%d-%m-%Y', '%d/%m/%Y'):
            try:
                return datetime.strptime(date_str.strip(), fmt).date()
            except ValueError:
                continue
        return False

    def _detect_channel(self, text):
        m = re.search(r'Settlement\s*Position\s*\(([^)]+)\)', text, re.I)
        if m:
            ch = m.group(1).strip().upper()
            if ch in ('ATM', 'POS', 'IB', 'MFS', 'QR'):
                return ch
        upper = text.upper()
        for ch in ('ATM', 'POS', 'IB', 'MFS', 'QR'):
            if f'POSITION ({ch})' in upper or f'POSITION({ch})' in upper:
                return ch
        return False

    # ------------------------------------------------------------------
    # Cell helpers
    # ------------------------------------------------------------------
    EMPTY_MARKERS = {'', '-', '–', '−', '.', 'none', 'null', 'n/a', 'na', 'nil'}

    def _normalize_row(self, row, expected_len=13):
        cells = []
        for c in (row or []):
            if c is None:
                cells.append('')
            else:
                cells.append(str(c).replace('\n', ' ').strip())
        while len(cells) < expected_len:
            cells.append('')
        return cells[:expected_len]

    def _is_empty(self, value):
        if value is None:
            return True
        s = str(value).strip().lower().replace(',', '')
        return s in self.EMPTY_MARKERS

    def _to_int(self, value):
        if self._is_empty(value):
            return 0
        s = str(value).strip().replace(',', '').replace('−', '-').replace('–', '-')
        try:
            return int(float(s))
        except (ValueError, TypeError):
            return 0

    def _to_float(self, value):
        if self._is_empty(value):
            return 0.0
        s = str(value).strip().replace(',', '').replace('−', '-').replace('–', '-')
        try:
            return float(s)
        except (ValueError, TypeError):
            return 0.0

    TRANS_TYPES = {
        'BI', 'MS', 'CW', 'FT-01', 'FT-02', 'FT', 'Cbk', '2Prs', '2Cbk',
        'Reversals', 'SubTotal', 'RP', 'RP-Cbk', 'RP-2Prs', 'RP-2Cbk',
        'CA', 'CA-Cbk', 'CA-2Prs', 'CA-2Cbk',
        'FT-W2W', 'FT-W2A', 'FT-W2C', 'FT-A2W', 'FT-C2W', 'MP',
        'MP-RM', 'MP-MM', 'GrandTotal',
    }

    def _find_trans_type(self, cells):
        c0 = cells[0].replace(' ', '').replace('\n', '') if cells else ''
        if c0.lower() in ('grandtotal', 'grand total'):
            return 'GrandTotal'
        if len(cells) > 2:
            clean = cells[2].replace(' ', '').replace('\n', '')
            if clean in self.TRANS_TYPES:
                return 'SubTotal' if clean.lower().startswith('sub') else clean
            if clean.lower() in ('subtotal', 'sub total'):
                return 'SubTotal'
        for cell in cells:
            clean = cell.replace(' ', '').replace('\n', '')
            if clean in self.TRANS_TYPES:
                return 'SubTotal' if clean.lower().startswith('sub') else clean
            if clean.lower() in ('grandtotal', 'grand total'):
                return 'GrandTotal'
        return None

    def _is_meghnapay_row(self, cells):
        joined = ' '.join(cells).lower().replace(' ', '')
        return 'meghnapay' in joined or 'settlementamountfornpsb' in joined

    def _extract_amounts(self, cells):
        """PDF cols: 3=IssNo 4=IssAmt 5=IssFee 6=AcqNo 7=AcqAmt 8=AcqFee
                     9=PlatformFee 10=TotalFees 11=TotalTransAmt 12=Net/Gross"""
        return {
            'iss_no': self._to_int(cells[3]),
            'iss_amt': self._to_float(cells[4]),
            'iss_fee': self._to_float(cells[5]),
            'acq_no': self._to_int(cells[6]),
            'acq_amt': self._to_float(cells[7]),
            'acq_fee': self._to_float(cells[8]),
            'platform_fee': self._to_float(cells[9]),
            'total_fees': self._to_float(cells[10]),
            'total_trans_amount': self._to_float(cells[11]),
            'net_amount': self._to_float(cells[12]),
        }

    # ------------------------------------------------------------------
    # Summary Page
    # Final Excel format:
    #   Issuer/Acquirer | Delivery Channel | Trans Type | No.of Trans |
    #   Trans Amount | Fees/IRF | Platform Fee | Net Amount
    # ------------------------------------------------------------------
    def _parse_summary_page(self, page, log):
        """
        Build summary lines matching the Excel export format:

        Columns:
          Issuer/Acquirer | Delivery Channel | Trans Type |
          No. of Trans | Trans Amount | Fees/IRF | Platform Fee | Net Amount

        Rules:
          1. Normal TransType rows → No.of Trans + Trans Amount (+ Platform/Net when present)
          2. Extra row TransType="Fees/IRF Amount" → fee value ONLY in Fees/IRF column
          3. Near end: MeghnaPay label in Issuer/Acquirer, value in Net Amount
          4. Last: Grand Total label in Issuer/Acquirer, value in Net Amount
        """
        tables = page.extract_tables()
        rows = []
        sl = 1
        current_channel = None
        channel_iss_fee = 0.0
        channel_acq_fee = 0.0

        if not tables:
            log.append('Summary: no tables found')
            return rows

        def flush_channel_fees():
            """Append Fees/IRF Amount rows for the current channel (value in Fees/IRF col)."""
            nonlocal sl, channel_iss_fee, channel_acq_fee, current_channel, rows
            if not current_channel:
                return
            if channel_iss_fee:
                rows.append({
                    'sequence': sl,
                    'issuer_acquirer': 'Issuing',
                    'delivery_channel': current_channel,
                    'trans_type': 'Fees/IRF Amount',
                    'no_of_trans': 0,
                    'trans_amount': 0.0,
                    'fees_irf_amount': channel_iss_fee,  # MUST be Fees/IRF column
                    'platform_fee': 0.0,
                    'net_amount': 0.0,
                })
                sl += 1
                log.append(f'  Fees/IRF Amount Issuing {current_channel} = {channel_iss_fee}')
            if channel_acq_fee:
                rows.append({
                    'sequence': sl,
                    'issuer_acquirer': 'Acquiring/Beneficiary',
                    'delivery_channel': current_channel,
                    'trans_type': 'Fees/IRF Amount',
                    'no_of_trans': 0,
                    'trans_amount': 0.0,
                    'fees_irf_amount': channel_acq_fee,  # MUST be Fees/IRF column
                    'platform_fee': 0.0,
                    'net_amount': 0.0,
                })
                sl += 1
                log.append(f'  Fees/IRF Amount Acquiring {current_channel} = {channel_acq_fee}')
            channel_iss_fee = 0.0
            channel_acq_fee = 0.0

        table = tables[0]
        for raw_row in table[2:]:
            cells = self._normalize_row(raw_row)
            joined_nospace = ''.join(cells).lower().replace(' ', '')

            # ============================================================
            # 1) MeghnaPay special row (second-to-last in Excel)
            #    Label → Issuer/Acquirer ; value → Net Amount
            # ============================================================
            if 'meghnapay' in joined_nospace or 'settlementamountfornpsb' in joined_nospace:
                flush_channel_fees()  # finish last channel fees first
                amount = 0.0
                for c in reversed(cells):
                    val = self._to_float(c)
                    if val:
                        amount = val
                        break
                rows.append({
                    'sequence': sl,
                    'issuer_acquirer': 'Settlement amount for NPSB transactions and charges of MeghnaPay',
                    'delivery_channel': '',
                    'trans_type': '',
                    'no_of_trans': 0,
                    'trans_amount': 0.0,
                    'fees_irf_amount': 0.0,
                    'platform_fee': 0.0,
                    'net_amount': amount,  # 58.59 — only special rows keep Net Amount
                    'is_special': True,
                })
                sl += 1
                log.append(f'  MeghnaPay row SL#={sl-1} Net Amount = {amount}')
                continue

            # ============================================================
            # 2) Grand Total special row (LAST in Excel)
            #    Label → Issuer/Acquirer ; value → Net Amount
            # ============================================================
            c0 = cells[0].replace(' ', '').replace('\n', '').lower()
            is_grand = c0 in ('grandtotal', 'grandtotal') or c0 == 'grandtotal'
            if not is_grand:
                # also scan all cells
                for cell in cells:
                    if cell.replace(' ', '').replace('\n', '').lower() in ('grandtotal', 'grand total'):
                        is_grand = True
                        break
            if is_grand or c0 == 'grandtotal':
                flush_channel_fees()
                amts = self._extract_amounts(cells)
                net = amts['net_amount']
                if not net:
                    # fallback: last numeric cell
                    for c in reversed(cells):
                        val = self._to_float(c)
                        if val:
                            net = val
                            break
                rows.append({
                    'sequence': sl,
                    'issuer_acquirer': 'Grand Total',
                    'delivery_channel': '',
                    'trans_type': '',
                    'no_of_trans': 0,
                    'trans_amount': 0.0,
                    'fees_irf_amount': 0.0,
                    'platform_fee': 0.0,
                    'net_amount': net,  # 1,01,62,963.00 — only special rows keep Net Amount
                    'is_special': True,
                })
                sl += 1
                log.append(f'  Grand Total row SL#={sl-1} Net Amount = {net}')
                continue

            # ============================================================
            # 3) Normal channel / TransType rows
            # ============================================================
            ch = cells[1].upper().replace(' ', '')
            if ch in ('ATM', 'POS', 'IB', 'MFS', 'QR'):
                if current_channel and current_channel != ch:
                    flush_channel_fees()
                current_channel = ch

            trans_type = self._find_trans_type(cells)
            if not trans_type or trans_type == 'GrandTotal':
                continue

            channel = current_channel or 'Unknown'
            amts = self._extract_amounts(cells)

            # Remember fees for this channel (shown on first data row in PDF)
            if amts['iss_fee']:
                channel_iss_fee = amts['iss_fee']
            if amts['acq_fee']:
                channel_acq_fee = amts['acq_fee']

            # Issuing
            rows.append({
                'sequence': sl,
                'issuer_acquirer': 'Issuing',
                'delivery_channel': channel,
                'trans_type': trans_type,
                'no_of_trans': amts['iss_no'],
                'trans_amount': amts['iss_amt'],
                'fees_irf_amount': 0.0,
                'platform_fee': amts['platform_fee'],
                'net_amount': 0.0,  # only MeghnaPay / Grand Total store Net Amount
            })
            sl += 1

            # Acquiring/Beneficiary
            rows.append({
                'sequence': sl,
                'issuer_acquirer': 'Acquiring/Beneficiary',
                'delivery_channel': channel,
                'trans_type': trans_type,
                'no_of_trans': amts['acq_no'],
                'trans_amount': amts['acq_amt'],
                'fees_irf_amount': 0.0,
                'platform_fee': amts['platform_fee'],
                'net_amount': 0.0,  # only MeghnaPay / Grand Total store Net Amount
            })
            sl += 1

        # Safety: if PDF had no GrandTotal/MeghnaPay, still flush fees
        flush_channel_fees()

        log.append(f'Summary page: produced {len(rows)} rows (Excel format)')
        return rows

