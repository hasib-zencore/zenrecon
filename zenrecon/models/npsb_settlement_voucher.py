class NpsbSettlementVoucherRun(models.Model):
    _name = "npsb.settlement.voucher.run"
    _description = "NPSB Settlement Voucher Run"
    _inherit = ["mail.thread", "mail.activity.mixin"]
    _order = "create_date desc, id desc"
    _check_company_auto = True

    name = fields.Char(
        string="Run Reference", default=lambda self: _("New"), readonly=True,
        copy=False, tracking=True,
    )
    company_id = fields.Many2one(
        "res.company", required=True, default=lambda self: self.env.company,
        index=True, tracking=True,
    )
    transaction_date = fields.Date(
        string="Transaction Business Date", required=True, index=True, tracking=True,
    )
    settlement_date = fields.Date(
        string="Settlement Business Date", required=True, index=True, tracking=True,
    )
    source_report_id = fields.Many2one(
        "npsb.settlement.report", string="Resolved Settlement Report",
        readonly=True, copy=False, ondelete="restrict", check_company=True,
    )
    configuration_ids = fields.Many2many(
        "npsb.settlement.configuration", "npsb_voucher_run_configuration_rel",
        "run_id", "configuration_id", string="Applied Configurations",
        readonly=True, copy=False, check_company=True,
    )
    line_ids = fields.One2many(
        "npsb.settlement.voucher.run.line", "run_id", string="Voucher Lines",
        readonly=True, copy=False,
    )
    configuration_count = fields.Integer(compute="_compute_totals")
    line_count = fields.Integer(compute="_compute_totals")
    debit_total = fields.Float(compute="_compute_totals", digits=(20, 2))
    credit_total = fields.Float(compute="_compute_totals", digits=(20, 2))
    difference = fields.Float(compute="_compute_totals", digits=(20, 2))
    is_balanced = fields.Boolean(compute="_compute_totals")
    currency_code = fields.Char(default="BDT", readonly=True)
    state = fields.Selection(
        [("draft", "Draft"), ("generated", "Generated"), ("exception", "Exception")],
        default="draft", required=True, readonly=True, copy=False, index=True,
        tracking=True,
    )
    output_file = fields.Binary(
        string="NPSB Voucher Report", attachment=True, readonly=True, copy=False,
    )
    output_filename = fields.Char(readonly=True, copy=False)
    generated_at = fields.Datetime(readonly=True, copy=False)
    generated_by_id = fields.Many2one(
        "res.users", string="Generated By", readonly=True, copy=False,
    )

    _date_pair_company_unique = models.Constraint(
        "UNIQUE(company_id, transaction_date, settlement_date)",
        "An NPSB voucher run already exists for these business dates.",
    )

    @api.model_create_multi
    def create(self, vals_list):
        for values in vals_list:
            if not values.get("name") or values.get("name") == _("New"):
                values["name"] = (
                    self.env["ir.sequence"].next_by_code("npsb.settlement.voucher.run")
                    or _("New")
                )
        return super().create(vals_list)

    @api.depends("configuration_ids", "line_ids.debit_amount", "line_ids.credit_amount")
    def _compute_totals(self):
        for run in self:
            debit = sum(run.line_ids.mapped("debit_amount"))
            credit = sum(run.line_ids.mapped("credit_amount"))
            run.configuration_count = len(run.configuration_ids)
            run.line_count = len(run.line_ids)
            run.debit_total = debit
            run.credit_total = credit
            run.difference = debit - credit
            run.is_balanced = bool(run.line_ids) and abs(debit - credit) < 0.01

    def _resolve_source_report(self):
        self.ensure_one()
        reports = self.env["npsb.settlement.report"].search([
            ("company_id", "=", self.company_id.id),
            ("state", "=", "processed"),
            ("transaction_date", "=", self.transaction_date),
            ("settlement_date", "=", self.settlement_date),
        ])
        if not reports:
            raise UserError(_(
                "No processed NPSB Settlement Report was found for Transaction Date %s "
                "and Settlement Date %s."
            ) % (self.transaction_date, self.settlement_date))
        if len(reports) > 1:
            fingerprints = {report._pdf_digest() for report in reports}
            if len(fingerprints) == 1:
                # Historical duplicate uploads contain the same source data.
                # Prefer the latest processed copy without deleting audit data.
                return reports.sorted(
                    lambda report: (report.create_date, report.id), reverse=True
                )[:1]
            raise UserError(_(
                "Different processed NPSB Settlement Reports exist for these dates. "
                "Keep one authoritative revision before generating the voucher: %s"
            ) % ", ".join(reports.mapped("display_name")))
        return reports

    @staticmethod
    def _same_dimension(source_line, mapping_line):
        return all(
            (source_line[field_name] or "") == (mapping_line[target_name] or "")
            for field_name, target_name in (
                ("issuer_acquirer", "business_mode"),
                ("delivery_channel", "delivery_channel"),
                ("trans_type", "transaction_type"),
            )
        )

    def _prepare_voucher_lines(self, report, configurations):
        self.ensure_one()
        summary_lines = self.env["npsb.settlement.summary.line"].search([
            ("report_id", "=", report.id),
        ])
        if not summary_lines:
            raise UserError(_("The resolved NPSB report contains no Settlement Summary data."))

        values_list = []
        problems = []
        applied_configurations = self.env["npsb.settlement.configuration"]
        sequence = 10
        for configuration in configurations.sorted(lambda item: (item.name or "", item.id)):
            matched_sources = summary_lines.filtered(
                lambda line, config=configuration: config._matches_filters(
                    line, include_source_dates=False
                )
            )
            if not matched_sources:
                continue
            applied_configurations |= configuration
            mappings = configuration.line_ids.filtered("include_in_voucher")
            incomplete = mappings.filtered(
                lambda line: not line.posting_indicator or not line.gl_number or not line.gl_name
            )
            if not mappings:
                problems.append(_("%s has no enabled accounting rules") % configuration.display_name)
                continue
            if incomplete:
                problems.append(_("%s has %s incomplete accounting rule(s)") % (
                    configuration.display_name, len(incomplete),
                ))
                continue

            generated_for_configuration = 0
            for mapping in mappings.sorted(lambda line: (line.sequence, line.id)):
                dimension_rows = matched_sources.filtered(
                    lambda source, target=mapping: self._same_dimension(source, target)
                )
                amount = sum(abs(value or 0.0) for value in dimension_rows.mapped(mapping.amount_source))
                if not amount:
                    continue
                is_debit = mapping.posting_indicator == "DR"
                values_list.append({
                    "run_id": self.id,
                    "sequence": sequence,
                    "configuration_id": configuration.id,
                    "configuration_line_id": mapping.id,
                    "source_report_id": report.id,
                    "business_mode": mapping.business_mode,
                    "delivery_channel": mapping.delivery_channel,
                    "transaction_type": mapping.transaction_type,
                    "amount_source": mapping.amount_source,
                    "source_row_count": len(dimension_rows),
                    "source_amount": amount,
                    "posting_indicator": mapping.posting_indicator,
                    "gl_number": mapping.gl_number,
                    "gl_name": mapping.gl_name,
                    "remarks": mapping.debit_remarks if is_debit else mapping.credit_remarks,
                    "debit_amount": amount if is_debit else 0.0,
                    "credit_amount": amount if not is_debit else 0.0,
                })
                sequence += 10
                generated_for_configuration += 1
            if not generated_for_configuration:
                problems.append(_("%s produced no non-zero voucher amounts") % configuration.display_name)

        if problems:
            raise UserError(_(
                "All NPSB configurations for the resolved report must be applicable and complete:\n- %s"
            ) % "\n- ".join(problems))
        if not applied_configurations:
            raise UserError(_(
                "No NPSB Settlement Configuration matches the resolved report's Summary data."
            ))
        if not values_list:
            raise UserError(_("The NPSB configurations produced no voucher lines."))
        return values_list, applied_configurations

    def action_generate(self):
        self.ensure_one()
        report = self._resolve_source_report()
        configurations = self.env["npsb.settlement.configuration"].search([
            ("company_id", "=", self.company_id.id),
        ])
        if not configurations:
            raise UserError(_(
                "No NPSB Settlement Configuration was found for %s. "
                "Create the required configurations before generating the voucher."
            ) % report.display_name)

        line_values, applied_configurations = self._prepare_voucher_lines(
            report, configurations
        )
        self.line_ids.unlink()
        self.env["npsb.settlement.voucher.run.line"].create(line_values)
        self.write({
            "source_report_id": report.id,
            "configuration_ids": [(6, 0, applied_configurations.ids)],
            "generated_at": fields.Datetime.now(),
            "generated_by_id": self.env.user.id,
        })
        self.write({"state": "generated" if self.is_balanced else "exception"})
        content = self._build_xlsx()
        self.write({
            "output_file": base64.b64encode(content),
            "output_filename": "%s.xlsx" % self.name.replace("/", "-"),
        })
        self.message_post(body=_(
            "NPSB voucher generated from %s using %s configuration(s) and %s voucher line(s)."
        ) % (report.display_name, len(applied_configurations), len(self.line_ids)))
        return {
            "type": "ir.actions.client",
            "tag": "display_notification",
            "params": {
                "title": _("NPSB voucher generated"),
                "message": _("The voucher is balanced and ready to download.")
                if self.is_balanced else _("The voucher was generated with a debit/credit exception."),
                "type": "success" if self.is_balanced else "warning",
                "next": {"type": "ir.actions.client", "tag": "reload"},
            },
        }

    def action_reset_draft(self):
        self.ensure_one()
        self.line_ids.unlink()
        self.write({
            "source_report_id": False,
            "configuration_ids": [(5, 0, 0)],
            "state": "draft",
            "output_file": False,
            "output_filename": False,
            "generated_at": False,
            "generated_by_id": False,
        })
        return {"type": "ir.actions.client", "tag": "reload"}

    def action_download(self):
        self.ensure_one()
        if not self.output_file:
            raise UserError(_("Generate the NPSB voucher before downloading it."))
        return {
            "type": "ir.actions.act_url",
            "url": "/web/content/%s/%s/output_file/%s?download=true" % (
                self._name, self.id, self.output_filename,
            ),
            "target": "self",
        }

    def _build_xlsx(self):
        self.ensure_one()
        if Workbook is None:
            raise UserError(_("Python library 'openpyxl' is required to create the voucher report."))

        workbook = Workbook()
        sheet = workbook.active
        sheet.title = "NPSB Voucher"
        navy = "123B5D"
        dark_navy = "0B2942"
        teal = "087F8C"
        purple = "71356F"
        pale_blue = "EDF5F9"
        pale_green = "E6F5E9"
        pale_red = "FDECEC"
        total_green = "D7F0DC"
        grey = "526173"
        light_grey = "F4F7F9"
        white = "FFFFFF"
        thin = Side(style="thin", color="CAD6DE")
        border = Border(top=thin, bottom=thin, left=thin, right=thin)
        money_format = '#,##0.00;[Red]-#,##0.00'
        bank_name = (self.source_report_id.bank_name or "").strip()

        def style_range(row, start_column, end_column, fill, font, alignment=None):
            for column in range(start_column, end_column + 1):
                cell = sheet.cell(row, column)
                cell.fill = PatternFill("solid", fgColor=fill)
                cell.font = font
                cell.border = border
                if alignment:
                    cell.alignment = alignment

        # Branded header. The bank name is sourced from the parsed daily report.
        sheet.merge_cells("A1:K1")
        sheet["A1"] = "BANK RECONCILIATION VOUCHER"
        sheet["A1"].font = Font(size=20, bold=True, color=white)
        sheet["A1"].fill = PatternFill("solid", fgColor=dark_navy)
        sheet["A1"].alignment = Alignment(horizontal="left", vertical="center", indent=1)
        sheet.row_dimensions[1].height = 38

        sheet.merge_cells("A2:H2")
        sheet["A2"] = bank_name
        sheet["A2"].font = Font(size=14, bold=True, color=navy)
        sheet["A2"].alignment = Alignment(horizontal="left", vertical="center", indent=1)
        sheet.merge_cells("I2:K2")
        sheet["I2"] = "SETTLEMENT DATE  |  %s" % fields.Date.to_string(self.settlement_date)
        sheet["I2"].font = Font(size=11, bold=True, color=navy)
        sheet["I2"].alignment = Alignment(horizontal="center", vertical="center")
        sheet.row_dimensions[2].height = 27

        sheet.merge_cells("A3:K3")
        sheet["A3"] = "NPSB SETTLEMENT  •  BDT"
        sheet["A3"].font = Font(size=11, bold=True, color=teal)
        sheet["A3"].alignment = Alignment(horizontal="left", vertical="center", indent=1)

        metadata = (
            ("Voucher Reference", self.name, "Source Report", self.source_report_id.display_name),
            ("Transaction Date", fields.Date.to_string(self.transaction_date),
             "Generated At", fields.Datetime.to_string(self.generated_at)),
            ("Prepared By", self.generated_by_id.name or "", "Currency", "BDT"),
        )
        for row_index, (left_label, left_value, right_label, right_value) in enumerate(metadata, 5):
            sheet.cell(row_index, 1, left_label).font = Font(bold=True, color=grey)
            sheet.merge_cells(start_row=row_index, start_column=2, end_row=row_index, end_column=5)
            sheet.cell(row_index, 2, left_value).font = Font(color=navy)
            sheet.cell(row_index, 7, right_label).font = Font(bold=True, color=grey)
            sheet.merge_cells(start_row=row_index, start_column=8, end_row=row_index, end_column=11)
            sheet.cell(row_index, 8, right_value).font = Font(color=navy)

        debit_lines = self.line_ids.filtered(lambda line: bool(line.debit_amount)).sorted("sequence")
        credit_lines = self.line_ids.filtered(lambda line: bool(line.credit_amount)).sorted("sequence")
        section_row = 9
        header_row = 10
        sheet.merge_cells(start_row=section_row, start_column=1, end_row=section_row, end_column=5)
        sheet.cell(section_row, 1, "↓  DEBIT ENTRIES")
        style_range(
            section_row, 1, 5, teal, Font(size=12, bold=True, color=white),
            Alignment(horizontal="left", vertical="center", indent=1),
        )
        sheet.merge_cells(start_row=section_row, start_column=7, end_row=section_row, end_column=11)
        sheet.cell(section_row, 7, "↑  CREDIT ENTRIES")
        style_range(
            section_row, 7, 11, purple, Font(size=12, bold=True, color=white),
            Alignment(horizontal="left", vertical="center", indent=1),
        )
        sheet.row_dimensions[section_row].height = 27

        for start_column, labels in (
            (1, ("SL", "GL Number", "GL Name", "Debit Amount", "Debit Remarks")),
            (7, ("SL", "GL Number", "GL Name", "Credit Amount", "Credit Remarks")),
        ):
            for offset, label in enumerate(labels):
                cell = sheet.cell(header_row, start_column + offset, label)
                cell.fill = PatternFill("solid", fgColor=navy)
                cell.font = Font(bold=True, color=white)
                cell.border = border
                cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        sheet.row_dimensions[header_row].height = 28

        display_count = max(len(debit_lines), len(credit_lines), 6)
        for index in range(display_count):
            row = header_row + index + 1
            row_fill = pale_blue if index % 2 == 0 else white
            debit = debit_lines[index] if index < len(debit_lines) else False
            credit = credit_lines[index] if index < len(credit_lines) else False
            debit_values = (
                index + 1 if debit else "", debit.gl_number if debit else "",
                debit.gl_name if debit else "", debit.debit_amount if debit else "",
                debit.remarks or "" if debit else "",
            )
            credit_values = (
                index + 1 if credit else "", credit.gl_number if credit else "",
                credit.gl_name if credit else "", credit.credit_amount if credit else "",
                credit.remarks or "" if credit else "",
            )
            for start_column, values in ((1, debit_values), (7, credit_values)):
                for offset, value in enumerate(values):
                    cell = sheet.cell(row, start_column + offset, value)
                    cell.fill = PatternFill("solid", fgColor=row_fill)
                    cell.border = border
                    cell.alignment = Alignment(
                        horizontal="right" if offset == 3 else ("center" if offset == 0 else "left"),
                        vertical="center", wrap_text=True,
                    )
                    if offset == 3 and value != "":
                        cell.number_format = money_format
            sheet.row_dimensions[row].height = 25

        total_row = header_row + display_count + 1
        sheet.merge_cells(start_row=total_row, start_column=1, end_row=total_row, end_column=3)
        sheet.cell(total_row, 1, "TOTAL DEBIT AMOUNT")
        sheet.cell(total_row, 4, self.debit_total).number_format = money_format
        style_range(
            total_row, 1, 5, total_green, Font(bold=True, color=navy),
            Alignment(horizontal="right", vertical="center"),
        )
        sheet.merge_cells(start_row=total_row, start_column=7, end_row=total_row, end_column=9)
        sheet.cell(total_row, 7, "TOTAL CREDIT AMOUNT")
        sheet.cell(total_row, 10, self.credit_total).number_format = money_format
        style_range(
            total_row, 7, 11, total_green, Font(bold=True, color=navy),
            Alignment(horizontal="right", vertical="center"),
        )
        sheet.row_dimensions[total_row].height = 28

        status_row = total_row + 2
        sheet.merge_cells(start_row=status_row, start_column=1, end_row=status_row, end_column=11)
        status = "BALANCED" if self.is_balanced else "EXCEPTION"
        sheet.cell(status_row, 1, "%s   |   DIFFERENCE: BDT %s" % (status, f"{self.difference:,.2f}"))
        sheet.cell(status_row, 1).font = Font(
            size=12, bold=True, color="237A3B" if self.is_balanced else "B42318"
        )
        sheet.cell(status_row, 1).fill = PatternFill(
            "solid", fgColor=pale_green if self.is_balanced else pale_red
        )
        sheet.cell(status_row, 1).alignment = Alignment(horizontal="center", vertical="center")
        sheet.row_dimensions[status_row].height = 30

        signature_row = status_row + 4
        signatures = (
            (1, 3, "MAKER", self.generated_by_id.name or ""),
            (5, 7, "CHECKER", ""),
            (9, 11, "APPROVER", ""),
        )
        for start, end, label, name in signatures:
            sheet.merge_cells(start_row=signature_row, start_column=start, end_row=signature_row, end_column=end)
            sheet.cell(signature_row, start, name or "________________________")
            sheet.cell(signature_row, start).alignment = Alignment(horizontal="center")
            sheet.merge_cells(start_row=signature_row + 1, start_column=start, end_row=signature_row + 1, end_column=end)
            label_cell = sheet.cell(signature_row + 1, start, label)
            label_cell.font = Font(bold=True, color=grey)
            label_cell.alignment = Alignment(horizontal="center")

        widths = (6, 15, 28, 18, 36, 3, 6, 15, 28, 18, 36)
        for column, width in enumerate(widths, 1):
            sheet.column_dimensions[get_column_letter(column)].width = width
        sheet.column_dimensions["F"].fill = PatternFill("solid", fgColor=light_grey)
        sheet.freeze_panes = "A11"
        sheet.sheet_view.showGridLines = False
        sheet.page_setup.orientation = "landscape"
        sheet.page_setup.paperSize = sheet.PAPERSIZE_A4
        sheet.page_setup.fitToWidth = 1
        sheet.page_setup.fitToHeight = 0
        sheet.sheet_properties.pageSetUpPr.fitToPage = True
        sheet.print_title_rows = "$1:$10"
        sheet.print_area = "A1:K%s" % (signature_row + 1)
        sheet.oddFooter.center.text = "Page &P of &N"
        sheet.oddFooter.right.text = "NPSB Settlement Voucher"

        # A separate audit sheet keeps full reconciliation traceability without
        # crowding the formal voucher presented for approval.
        audit = workbook.create_sheet("Audit Details")
        audit_headers = [
            "SL", "Configuration", "Business Mode", "Delivery Channel",
            "Transaction Type", "Amount Source", "GL Number", "GL Name",
            "Remarks", "Debit (BDT)", "Credit (BDT)",
        ]
        audit.merge_cells("A1:K1")
        audit["A1"] = "%s — NPSB VOUCHER AUDIT DETAILS" % bank_name
        audit["A1"].font = Font(size=14, bold=True, color=white)
        audit["A1"].fill = PatternFill("solid", fgColor=dark_navy)
        audit["A1"].alignment = Alignment(horizontal="center")
        for column, label in enumerate(audit_headers, 1):
            cell = audit.cell(3, column, label)
            cell.font = Font(bold=True, color=white)
            cell.fill = PatternFill("solid", fgColor=navy)
            cell.border = border
            cell.alignment = Alignment(horizontal="center", wrap_text=True)
        for row_index, line in enumerate(self.line_ids.sorted("sequence"), 4):
            values = (
                row_index - 3, line.configuration_id.display_name,
                line.business_mode or "(Blank)", line.delivery_channel or "(Blank)",
                line.transaction_type or "(Blank)", AMOUNT_FIELDS.get(line.amount_source),
                line.gl_number, line.gl_name, line.remarks or "",
                line.debit_amount, line.credit_amount,
            )
            for column, value in enumerate(values, 1):
                cell = audit.cell(row_index, column, value)
                cell.fill = PatternFill("solid", fgColor=pale_blue if row_index % 2 == 0 else white)
                cell.border = border
                cell.alignment = Alignment(vertical="top", wrap_text=True)
                if column in (10, 11):
                    cell.number_format = money_format
        audit_widths = (6, 22, 18, 18, 20, 20, 16, 24, 36, 18, 18)
        for column, width in enumerate(audit_widths, 1):
            audit.column_dimensions[get_column_letter(column)].width = width
        audit.freeze_panes = "A4"
        audit.auto_filter.ref = "A3:K%s" % (3 + len(self.line_ids))
        audit.sheet_view.showGridLines = False

        output = io.BytesIO()
        workbook.save(output)
        return output.getvalue()


class NpsbSettlementVoucherRunLine(models.Model):
    _name = "npsb.settlement.voucher.run.line"
    _description = "NPSB Settlement Voucher Line"
    _order = "run_id desc, sequence, id"
    _check_company_auto = True

    run_id = fields.Many2one(
        "npsb.settlement.voucher.run", required=True, ondelete="cascade",
        index=True, check_company=True,
    )
    company_id = fields.Many2one(related="run_id.company_id", store=True, index=True)
    sequence = fields.Integer(default=10, index=True)
    configuration_id = fields.Many2one(
        "npsb.settlement.configuration", required=True, ondelete="restrict",
        index=True, check_company=True,
    )
    configuration_line_id = fields.Many2one(
        "npsb.settlement.configuration.line", required=True, ondelete="restrict", index=True,
    )
    source_report_id = fields.Many2one(
        "npsb.settlement.report", required=True, ondelete="restrict",
        index=True, check_company=True,
    )
    business_mode = fields.Char(readonly=True)
    delivery_channel = fields.Char(readonly=True)
    transaction_type = fields.Char(readonly=True)
    amount_source = fields.Selection(
        [(key, label) for key, label in AMOUNT_FIELDS.items()],
        string="Amount Column", required=True, readonly=True,
    )
    source_row_count = fields.Integer(readonly=True)
    source_amount = fields.Float(readonly=True, digits=(20, 2))
    posting_indicator = fields.Selection(
        [("DR", "DR"), ("CR", "CR")], string="DR/CR", required=True, readonly=True,
    )
    gl_number = fields.Char(string="GL Number", required=True, readonly=True)
    gl_name = fields.Char(string="GL Name", required=True, readonly=True)
